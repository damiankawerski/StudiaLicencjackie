int get_inversions(long long A, long long B, long long C) {
    return (A > C) + (A > B) + (B > C);
}


long long get_compartment(bool &found) {
    int jump = 2;
    int A, B, C;
    C = time_jump(0);

    while(true) {

        A = C;
        B = time_jump(jump / 2);
        C = time_jump(jump / 2);

        if (A == C) {
            found = true;
            break;
        }

        if (get_inversions(A, B, C) % 2 != 0) {
            break;
        }

        jump *= 2;
    }

    return jump;
}

int search(long long high, long long low) {
    long long mid;
    long long A, B, C;
    C = time_jump(0);

    while(true) {

        mid = (low + high) / 2;

        if(mid % 2 != 0) {
            return mid;
        }

        A = C;
        B = time_jump(mid / 2);
        C = time_jump(mid / 2);

        if(A == C) {
            return mid;
        }


        if(get_inversions(A, B, C) % 2 == 0) {
            low = mid;
        } else {
            high = mid;
        }
    }
}

